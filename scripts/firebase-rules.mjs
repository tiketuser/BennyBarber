// Writes the Firebase security rules and project files from shop.config.ts (admin numbers, shop id, project).
// Run by `npm run deploy`, which also builds the site and uploads rules and site together.
import { writeFileSync } from 'node:fs';
import shop from '../shop.config.ts';

const e164 = (p) => '+972' + p.replace(/\D/g, '').replace(/^0/, '');
// The trial build (shops/trial) holds many shops in one project: each one's admins and end date are in its
// trialShops/{shopId} document, which only the outreach automation writes (with a service account, past these rules).
const trial = !!shop.trial;
const trialDoc = '/databases/$(database)/documents/trialShops/$(shopId)';
const admins = trial ? `get(${trialDoc}).data.adminPhonesE164` : JSON.stringify(shop.adminPhones.map(e164));
const shopPath = `/databases/$(database)/documents/shops/${trial ? '$(shopId)' : shop.shopId}`;
// Storage rules can't read Firestore on the trial project (that needs an IAM role on Storage's service agent), so
// with deploy credentials each trial shop's gallery admins are written into storage.rules from trialShops; the
// create-trial workflow redeploys them for every new shop. Without credentials (emulator tests) they're looked up.
let storageAdmins = 'firestore.get(/databases/(default)/documents/trialShops/$(shopId)).data.adminPhonesE164';
if (trial && process.env.GOOGLE_APPLICATION_CREDENTIALS) {
  const { applicationDefault, initializeApp } = await import('firebase-admin/app');
  const { getFirestore } = await import('firebase-admin/firestore');
  const db = getFirestore(initializeApp({ credential: applicationDefault(), projectId: shop.firebase.projectId }, 'rules'));
  const byShop = Object.fromEntries((await db.collection('trialShops').get()).docs.map((d) => [d.id, d.get('adminPhonesE164') ?? []]));
  storageAdmins = `${JSON.stringify(byShop)}.get(shopId, [])`;
}
const header = '// Generated by `npm run firebase:rules` from shop.config.ts. Edit scripts/firebase-rules.mjs, not this file.\n';

writeFileSync(
  'firestore.rules',
  `${header}rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {
${
  trial
    ? `    // Each trial shop's details, read by the app before it loads. Written only by the automation's service account.
    match /trialShops/{slug} {
      allow read: if true;
    }
    // A barber's own site (<siteId>.web.app) -> his slug.
    match /trialSites/{siteId} {
      allow read: if true;
    }

`
    : ''
}    match /shops/${trial ? '{shopId}' : shop.shopId} {
    // Admin numbers come from ${trial ? "the shop's trialShops document (adminPhonesE164)" : 'shop.config.ts adminPhones'}. The app's admin view is only a convenience; this is the real check.
    function isAdmin() {
      return request.auth != null && request.auth.token.get('phone_number', '') in ${admins};
    }
    // Trial shops: the shop exists, and new bookings only until its free week ends (trialEndsAt, a timestamp).
    function live() {
      return ${trial ? `exists(${trialDoc})` : 'true'};
    }
    function open() {
${
  trial
    ? `      let ends = get(${trialDoc}).data.get('trialEndsAt', null);
      return live() && (!(ends is timestamp) || request.time < ends);`
    : '      return true;'
}
    }
    // Customers sign in with their number and name only (an anonymous sign-in), so a typed number proves nothing:
    // what they booked is theirs by sign-in id (customerUid). Older SMS sign-ins also own by their verified number.
    function signedIn() {
      return request.auth != null;
    }
    function verified() {
      return request.auth.token.get('phone_number', null) is string;
    }
    // "+972521234567" -> "0521234567", the form the app stores.
    function phone() {
      let p = request.auth.token.phone_number;
      return '0' + p[4:p.size()];
    }
    function mine(a) {
      return a.get('customerUid', null) == request.auth.uid || (verified() && a.get('customerPhone', null) == phone());
    }
    // A new booking or waitlist entry carries its owner's sign-in id (and his verified number, if he has one).
    function ownedNew(a) {
      return a.get('customerUid', null) == request.auth.uid && a.get('customerPhone', null) is string
        && (!verified() || a.customerPhone == phone());
    }
    function appt(id) {
      return getAfter(${shopPath}/appointments/$(id)).data;
    }
    // The appointment is listed in its day's ledger with the same times.
    function inLedger(id, a) {
      return getAfter(${shopPath}/days/$(a.date)).data.busy.hasAny([{ 'id': id, 'start': a.start, 'end': a.end }]);
    }
    function ownsNew(date, e) {
      let a = appt(e.id);
      return mine(a) && a.status == 'booked' && a.date == date && a.start == e.start && a.end == e.end;
    }
    function ownsCancelled(e) {
      let a = appt(e.id);
      return mine(a) && a.status == 'cancelled';
    }
    // A customer may add one own new appointment to a day and/or take one own cancelled appointment off it.
    function customerLedgerChange(date) {
      let next = request.resource.data.busy;
      let prev = resource.data.busy;
      let added = next.removeAll(prev);
      let removed = prev.removeAll(next);
      return request.resource.data.keys().hasOnly(['busy'])
        && added.size() <= 1 && removed.size() <= 1 && added.size() + removed.size() >= 1
        && next.size() == prev.size() + added.size() - removed.size()
        && (added.size() == 0 || ownsNew(date, added[0]))
        && (removed.size() == 0 || ownsCancelled(removed[0]));
    }

      match /meta/{doc} {
        allow read: if true;
        allow write: if isAdmin();
      }
      match /services/{id} {
        allow read: if true;
        allow write: if isAdmin();
      }
      match /gallery/{id} {
        allow read: if true;
        allow write: if isAdmin();
      }
      match /users/{uid} {
        allow read: if isAdmin() || (request.auth != null && request.auth.uid == uid);
        allow write: if request.auth != null && request.auth.uid == uid && live();
      }
      match /blocks/{id} {
        allow read, write: if isAdmin();
      }
      // Busy ranges per day, without names: what customers see of other people's appointments.
      match /days/{date} {
        allow read: if true;
        allow write: if isAdmin();
        allow create: if signedIn() && open() && request.resource.data.keys().hasOnly(['busy'])
          && request.resource.data.busy.size() == 1 && ownsNew(date, request.resource.data.busy[0]);
        allow update: if signedIn() && customerLedgerChange(date) && (open() || request.resource.data.busy.size() < resource.data.busy.size());
      }
      match /appointments/{id} {
        allow read: if isAdmin() || (signedIn() && mine(resource.data));
        allow create: if isAdmin() || (signedIn() && open()
          && ownedNew(request.resource.data)
          && request.resource.data.status == 'booked'
          && request.resource.data.source == 'app'
          && inLedger(id, request.resource.data));
        allow update: if isAdmin() || (signedIn()
          && mine(resource.data)
          && resource.data.status == 'booked'
          && request.resource.data.status == 'cancelled'
          && request.resource.data.cancelledBy == 'customer'
          && request.resource.data.diff(resource.data).affectedKeys().hasOnly(['status', 'cancelledAt', 'cancelledBy', 'openingHandled'])
          && !inLedger(id, resource.data));
        allow delete: if isAdmin();
      }
      match /waitlist/{id} {
        allow read, delete: if isAdmin() || (signedIn() && mine(resource.data));
        allow create: if isAdmin() || (signedIn() && open() && ownedNew(request.resource.data));
      }
    }
  }
}
`,
);

writeFileSync(
  'storage.rules',
  `${header}rules_version = '2';
service firebase.storage {
  match /b/{bucket}/o {
    match /shops/${trial ? '{shopId}' : shop.shopId}/gallery/{file} {
      allow read: if true;
      allow write: if request.auth != null && request.auth.token.get('phone_number', '') in ${trial ? storageAdmins : admins}
        && request.resource.size < 3 * 1024 * 1024
        && request.resource.contentType.matches('image/.*');
    }
  }
}
`,
);

writeFileSync(
  'firebase.json',
  JSON.stringify(
    {
      firestore: { rules: 'firestore.rules' },
      storage: { rules: 'storage.rules' },
      // The site itself, free on <project>.web.app (already an authorized domain for SMS sign-in).
      hosting: {
        public: 'dist',
        ignore: ['firebase.json', '**/.*'],
        rewrites: [{ source: '**', destination: '/index.html' }],
        headers: [
          { source: '/sw.js', headers: [{ key: 'Cache-Control', value: 'no-cache' }] },
          { source: '/assets/**', headers: [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }] },
        ],
      },
      emulators: { auth: { port: 9099 }, firestore: { port: 8080 }, storage: { port: 9199 }, ui: { enabled: false }, singleProjectMode: true },
    },
    null,
    2,
  ) + '\n',
);
writeFileSync('.firebaserc', JSON.stringify({ projects: { default: shop.firebase.projectId } }, null, 2) + '\n');
console.log('wrote firestore.rules, storage.rules, firebase.json, .firebaserc for', shop.firebase.projectId);
